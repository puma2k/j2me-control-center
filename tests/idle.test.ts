import { test } from "node:test";
import assert from "node:assert/strict";
import { ScreenIdleTimer } from "../apps/web/src/idle.js";
test("screen sleeps after inactivity, wakes, and holds postpone sleep", (t) => {
  t.mock.timers.enable({ apis: ["setTimeout"] });
  const changes: boolean[] = [];
  const idle = new ScreenIdleTimer((sleeping) => changes.push(sleeping));
  t.mock.timers.tick(29999);
  assert.equal(idle.sleeping, false);
  idle.activity();
  t.mock.timers.tick(29999);
  assert.deepEqual(changes, []);
  t.mock.timers.tick(1);
  assert.deepEqual(changes, [true]);
  idle.releaseAll();
  assert.equal(idle.sleeping, true);
  assert.equal(idle.activity(), true);
  assert.deepEqual(changes, [true, false]);
  idle.hold("ArrowRight");
  t.mock.timers.tick(60000);
  assert.equal(idle.sleeping, false);
  idle.release("ArrowRight");
  t.mock.timers.tick(30000);
  assert.equal(idle.sleeping, true);
  idle.activity();
  idle.dispose();
  t.mock.timers.tick(30000);
  assert.equal(idle.sleeping, false);
});
